/** 조건에 맞는 자막 세트 하나를 고릅니다. 직전에 보여 준 자막(exclude)과 다른 세트를 우선합니다. */
export function pickCaptionSet(
  templateId: string,
  subjectId: string,
  moodId: MoodId,
  exclude?: readonly string[],
  name?: string,
): Set3 | undefined {
  const raw = CAPTION_POOL[`${templateId}:${subjectId}`]?.[moodId];
  if (!raw?.length) return undefined;
  const sets = raw.map((set) => set.map((c) => c.replace(/\{name\}/g, name || '크리에이터')) as Set3);
  const others = exclude ? sets.filter((s) => s.join('|') !== exclude.join('|')) : sets;
  const pool = others.length ? others : sets;
  return pool[Math.floor(Math.random() * pool.length)];
}
